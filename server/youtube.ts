import { Innertube, Log } from 'youtubei.js';
import { HttpError } from './errors.js';

/**
 * 유튜브 영상 정보·설명·자막 수집. youtubei.js(유튜브 웹 클라이언트 내부 API)를 기본 설정 그대로 쓴다.
 * 자막은 한국어 수동 자막 → 한국어 자동 생성 → 다른 언어 수동 → 다른 언어 자동 순으로 고른다.
 * 자막 본문을 못 받아오면(유튜브가 빈 응답을 주는 경우가 있다) 설명란만으로 진행하고 경고를 남긴다.
 */

Log.setLevel(Log.Level.ERROR);

export interface CaptionLine {
  startSec: number;
  text: string;
}

export interface VideoData {
  videoId: string;
  url: string;
  title?: string;
  channelName?: string;
  thumbnailUrl?: string;
  durationSec?: number;
  description: string;
  captions?: { languageCode: string; autoGenerated: boolean; lines: CaptionLine[] };
  /** 자막 트랙은 있었지만 본문을 못 가져왔을 때 */
  captionsUnavailable?: boolean;
}

let client: Promise<Innertube> | undefined;
const getClient = () => {
  client ??= Innertube.create({ lang: 'ko', location: 'KR' }).catch((e) => {
    client = undefined;
    throw e;
  });
  return client;
};

interface CaptionTrack {
  base_url: string;
  language_code: string;
  kind?: string;
}

function pickTrack(tracks: CaptionTrack[]): CaptionTrack | undefined {
  const isKo = (t: CaptionTrack) => t.language_code === 'ko' || t.language_code.startsWith('ko-');
  const isAuto = (t: CaptionTrack) => t.kind === 'asr';
  return (
    tracks.find((t) => isKo(t) && !isAuto(t)) ??
    tracks.find((t) => isKo(t) && isAuto(t)) ??
    tracks.find((t) => !isAuto(t)) ??
    tracks[0]
  );
}

interface Json3 {
  events?: Array<{ tStartMs?: number; segs?: Array<{ utf8?: string }> }>;
}

async function fetchCaptionLines(track: CaptionTrack): Promise<CaptionLine[]> {
  const url = new URL(track.base_url);
  url.searchParams.set('fmt', 'json3');
  const res = await fetch(url);
  if (!res.ok) return [];
  const body = await res.text();
  if (!body.trim()) return [];
  const data = JSON.parse(body) as Json3;
  return (data.events ?? [])
    .map((e) => ({
      startSec: Math.floor((e.tStartMs ?? 0) / 1000),
      text: (e.segs ?? []).map((s) => s.utf8 ?? '').join('').replace(/\s+/g, ' ').trim(),
    }))
    .filter((l) => l.text);
}

export async function fetchVideo(videoId: string): Promise<VideoData> {
  const yt = await getClient();
  let info;
  try {
    info = await yt.getInfo(videoId);
  } catch {
    throw new HttpError(502, '유튜브에서 영상 정보를 가져오지 못했어요. 잠시 후 다시 시도해 주세요.');
  }

  const status = info.playability_status?.status;
  if (status && status !== 'OK') {
    throw new HttpError(404, '영상을 볼 수 없어요. 비공개·삭제·연령 제한 영상인지 확인해 주세요.');
  }

  const basic = info.basic_info;
  const video: VideoData = {
    videoId,
    url: `https://www.youtube.com/watch?v=${videoId}`,
    title: basic.title,
    channelName: basic.channel?.name ?? basic.author,
    thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
    durationSec: basic.duration,
    description: basic.short_description ?? '',
  };

  const tracks = (info.captions?.caption_tracks ?? []) as CaptionTrack[];
  const track = pickTrack(tracks);
  if (track) {
    const lines = await fetchCaptionLines(track).catch(() => []);
    if (lines.length) {
      video.captions = { languageCode: track.language_code, autoGenerated: track.kind === 'asr', lines };
    } else {
      video.captionsUnavailable = true;
    }
  }
  return video;
}
